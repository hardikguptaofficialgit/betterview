export function normalizeIconName(name: string | undefined): string {
  if (!name) return '';
  let s = name.trim();
  s = s.replace(/([a-z0-9])([A-Z])/g, '$1-$2');
  s = s.toLowerCase();
  s = s.replace(/[\s_]+/g, '-');
  return s;
}

export function iconEl(name: string | undefined, size = 18): SVGElement {
  const norm = normalizeIconName(name);
  const node = norm && ICON_MAP[norm] ? ICON_MAP[norm] : Sparkles;
  const el = createElement(node, {
    width: String(size),
    height: String(size),
    'stroke-width': '1.75',
    'aria-hidden': 'true',
  });
  el.setAttribute('width', String(size));
  el.setAttribute('height', String(size));
  el.setAttribute('stroke-width', '1.75');
  el.setAttribute('aria-hidden', 'true');
  return el;
}
